/* vrocm.h — 这是 libvrocm.so 所有部分共有的词汇表：内部可见性标记以及设备绑定项，它防止运行时提供
 * 的索引变成数组偏移量。
 *
 * 这里没有任何内容。可能包含 hip* 或 hsa* 类型的文件，其他文件也不允许使用此类类型。这一规则使得该
 * 目录能够在没有安装 ROCm 且没有设备的情况下编译并运行，从而使得账本中的计算及配额解析测试能够正常
 * 进行——此目录中的其他内容只能在使用 AMD 平台上进行测试。
 *
 * 此处没有任何内容。可能调用 pthread_* 或 sem_* 符号。这些符号包含 GLIBC_2.34 的规范，而此库被预加
 * 载到可能使用较旧 glibc 的工作负载镜像中；该产品的兼容上限为 GLIBC_2.4，且 build.sh 也确认了这一
 * 点。因此，进程内排除机制属于编译器级原子化自旋锁，而跨进程排除机制则属于 fcntl() 记录锁，这两种
 * 机制均早于 2.4 版本。 */
#ifndef VROCM_COMMON_VROCM_H
#define VROCM_COMMON_VROCM_H

/* 隐藏状态，未导出。此代码被链接到预加载的库中，该库的可见接口必须完全与 HIP 的入口点一致：任何进
 * 入全局命名空间的通用符号，都会被工作负载进行拦截，且会与任何其他携带相同名称的预加载库产生冲突。
 * 第 1 种情况强调其不存在，而非依赖该属性。 */
#define VROCM_INTERNAL __attribute__((visibility("hidden")))

/* 受选择限制：索引是从设备句柄获取的，因此错误值绝不能成为数组偏移量。目前见过的容量最大的 AMD 主
 * 机拥有 8 块卡；仅 64 块卡就足以容纳该区域，而不会使区域过大。
 *
 * 受共享区域的布局约定限制。卡锁区域的大小由这个常量决定，其字节偏移量则是两个进程进行记录锁定的位
 * 置，因此如果在某个构建中提高该值而在另一个构建中不提高，会导致它们锁定不同的字节，从而无法实现协
 * 同工作。 */
#define VROCM_MAX_DEVICES 64

/* 这个账本为何在持有锁的情况下不等待任何线程？既非系统调用，也非等待操作：这条指令告诉核心，围绕它
 * 的循环属于锁旋转操作，这样可以释放原本可能堆积的推测性负载，减少消耗的电力，并让其他 SMT 实例获
 * 得其所需的槽位以完成解锁。此处明确说明而非在每次旋转操作旁说明，因此账本不会出现一个暂停的循环和
 * 一个不暂停的循环。 */
#if defined(__x86_64__) || defined(__i386__)
#define VROCM_SPIN_PAUSE() __builtin_ia32_pause()
#else
#define VROCM_SPIN_PAUSE() ((void)0)
#endif

#endif /* VROCM_COMMON_VROCM_H */
